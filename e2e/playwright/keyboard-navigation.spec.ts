import { expect, test, type Page } from '@playwright/test'

test.use({ viewport: { width: 1280, height: 800 } })
type TestWindow = typeof window & { polygonTestApi: {
  getDrawingState(): { ready: boolean; vertices: number }
  getMapState(): { stationary: boolean; editingReady: boolean }
  waitForPersistence(): Promise<void>
} }
const label = (page: Page, index: number) => page.getByTestId('polygon-item').nth(index).locator('.polygon-label')
async function mapFocus(page: Page) { await page.locator('#map .esri-view-surface').focus() }
async function create(page: Page, offset: number) {
  await mapFocus(page)
  await page.keyboard.press('n')
  await expect.poll(() => page.evaluate(() => (window as TestWindow).polygonTestApi.getDrawingState().ready)).toBe(true)
  const map = (await page.getByTestId('arcgis-map').boundingBox())!
  let vertices = 0
  for (const [x, y] of [[-65, -45], [65, -45], [0, 65]]) {
    await page.mouse.click(map.x + map.width / 2 + x + offset, map.y + map.height / 2 + y)
    vertices++
    await expect.poll(() => page.evaluate(() => (window as TestWindow).polygonTestApi.getDrawingState().vertices)).toBe(vertices)
  }
  await page.getByTestId('finish-drawing').click()
  await expect(page.getByTestId('finish-drawing')).toBeHidden()
}
async function twoPolygons(page: Page) { await create(page, -160); await create(page, 160) }

test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(page.getByTestId('map-ready')).toBeVisible()
})

test('A acessa a lista, as quatro setas selecionam sem expandir e E/Enter editam', async ({ page }) => {
  await page.keyboard.press('a') // Lista vazia não causa erro nem inicia uma ação.
  await expect(page.getByTestId('finish-drawing')).toBeHidden()
  await twoPolygons(page)
  await mapFocus(page)
  await page.keyboard.press('a')
  await expect(label(page, 0)).toBeFocused()
  for (const [key, index] of [['ArrowDown', 1], ['ArrowRight', 0], ['ArrowLeft', 1], ['ArrowUp', 0]] as const) {
    await page.keyboard.press(key)
    await expect(label(page, index)).toBeFocused()
    await expect(page.getByTestId('polygon-item').nth(index)).toHaveClass(/selected/)
    await expect(page.locator('.vertex-list')).toHaveCount(0)
  }
  await page.keyboard.press('e')
  await expect(page.getByTestId('polygon-name')).toHaveValue('Polígono 1')
  await mapFocus(page)
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('finish-drawing')).toBeHidden()
  await page.keyboard.press('a')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('polygon-name')).toHaveValue('Polígono 2')
})

test('D exclui o item com foco somente após confirmação, sem agir fora da lista', async ({ page }) => {
  await twoPolygons(page)
  await page.keyboard.press('a')
  // Foco por Tab ou clique pode estar em uma área diferente da seleção atual.
  await label(page, 1).focus()
  await page.keyboard.press('d')
  await expect(page.locator('#clear-dialog-description')).toContainText('Polígono 2')
  await expect(page.getByTestId('polygon-map-label')).toHaveCount(2)
  await expect(page.locator('#dismiss-clear')).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(page.locator('#confirm-clear')).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(page.locator('#dismiss-clear')).toBeFocused()
  await page.keyboard.press('ArrowLeft')
  await expect(page.locator('#confirm-clear')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('polygon-item')).toHaveCount(2)
  await expect(label(page, 1)).toBeFocused()
  await page.keyboard.press('d')
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('polygon-item')).toHaveCount(1)
  await expect(label(page, 0)).toHaveText('Polígono 1')
  await mapFocus(page)
  await page.keyboard.press('d')
  await expect(page.locator('#clear-dialog')).toBeHidden()
  await page.evaluate(() => (window as TestWindow).polygonTestApi.waitForPersistence())
  await page.reload()
  await expect(page.getByTestId('map-ready')).toBeVisible()
  await expect(label(page, 0)).toHaveText('Polígono 1')
})

test('setas e Tab circulam no modal de atalhos sem ativar os controles', async ({ page }) => {
  await page.getByTestId('keyboard-shortcuts-settings').click()
  const close = page.locator('#close-keyboard-shortcuts')
  const toggle = page.getByTestId('keyboard-shortcuts-dialog-enabled')
  await expect(close).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(toggle).toBeFocused()
  await expect(toggle).toBeChecked()
  await page.keyboard.press('Space')
  await expect(toggle).not.toBeChecked()
  await page.keyboard.press('ArrowDown')
  await expect(close).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(toggle).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('#keyboard-shortcuts-dialog')).toBeHidden()
  await expect(page.getByTestId('keyboard-shortcuts-enabled')).not.toBeChecked()
})

test('modal de alterações permite continuar ou descartar pelas setas e Enter', async ({ page }) => {
  await create(page, 0)
  await page.keyboard.press('a')
  await page.keyboard.press('Enter')
  await page.getByTestId('polygon-name').fill('')
  await page.getByTestId('polygon-name').pressSequentially('A D E')
  await expect(page.getByTestId('polygon-name')).toHaveValue('A D E')
  await expect(page.locator('#clear-dialog')).toBeHidden()
  await page.getByTestId('polygon-name').press('Escape')
  await expect(page.locator('#save-and-exit')).toBeFocused()
  await page.keyboard.press('ArrowUp')
  await expect(page.locator('#stay-editing')).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('polygon-name')).toHaveValue('A D E')
  await mapFocus(page)
  await page.keyboard.press('Escape')
  await page.keyboard.press('ArrowDown')
  await expect(page.locator('#discard-and-exit')).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('finish-drawing')).toBeHidden()
  await expect(label(page, 0)).toHaveText('Polígono 1')
  await expect(page.locator('.pin.selected')).toHaveCount(0)
})

test('atalhos desligados bloqueiam A/D/E e mantêm navegação nos modais', async ({ page }) => {
  await create(page, 0)
  await page.getByTestId('keyboard-shortcuts-enabled').uncheck()
  await mapFocus(page)
  await page.keyboard.press('a')
  await expect(label(page, 0)).not.toBeFocused()
  await label(page, 0).focus()
  await page.keyboard.press('d')
  await page.keyboard.press('e')
  await expect(page.locator('#clear-dialog')).toBeHidden()
  await expect(page.getByTestId('finish-drawing')).toBeHidden()
  await page.getByTestId('clear-polygons').click()
  await page.keyboard.press('ArrowRight')
  await expect(page.locator('#confirm-clear')).toBeFocused()
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.press('Enter')
  await expect(page.locator('#clear-dialog')).toBeHidden()
  await expect(page.getByTestId('polygon-item')).toHaveCount(1)
})

test('navegação da lista respeita bloqueio e permite destravar por L antes de editar', async ({ page }) => {
  await create(page, 0)
  await page.getByTestId('toggle-polygon-lock').click()
  await mapFocus(page)
  await page.keyboard.press('a')
  await expect(label(page, 0)).toBeFocused()
  await page.keyboard.press('e')
  await expect(page.getByTestId('finish-drawing')).toBeHidden()
  await expect(label(page, 0)).toBeFocused()
  await page.keyboard.press('l')
  await expect(label(page, 0)).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('polygon-name')).toBeVisible()
})

test('foco e seleção da lista sobrevivem à sincronização com o mapa separado', async ({ page }) => {
  await twoPolygons(page)
  const pending = page.waitForEvent('popup')
  await page.getByTestId('detach-map').click()
  const popup = await pending
  await expect(popup.getByTestId('map-ready')).toBeVisible({ timeout: 30_000 })
  await expect(page.locator('#connection-status')).toContainText('Mapa conectado')
  await page.keyboard.press('a')
  await expect(label(page, 0)).toBeFocused()
  await expect(popup.locator('.polygon-map-label.is-selected')).toHaveText('Polígono 1')
  await page.keyboard.press('ArrowDown')
  await expect(popup.locator('.polygon-map-label.is-selected')).toHaveText('Polígono 2')
  await expect(label(page, 1)).toBeFocused()
  await page.keyboard.press('e')
  await expect(page.getByTestId('polygon-name')).toHaveValue('Polígono 2')
  await page.getByTestId('polygon-name').fill('Rascunho')
  await expect(popup.getByTestId('polygon-name')).toHaveValue('Rascunho')
  await page.getByTestId('polygon-name').press('Escape')
  await expect(page.locator('#unsaved-edit-dialog')).toBeVisible()
  await page.keyboard.press('ArrowDown')
  await expect(page.locator('#discard-and-exit')).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('finish-drawing')).toBeHidden()
  await page.keyboard.press('a')
  await expect(label(page, 0)).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(label(page, 1)).toBeFocused()
  await page.keyboard.press('d')
  await expect(popup.locator('#clear-dialog')).toBeVisible()
  await expect(page.locator('#clear-dialog-description')).toContainText('Polígono 2')
  await page.keyboard.press('ArrowRight')
  await expect(page.locator('#confirm-clear')).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('polygon-item')).toHaveCount(1)
  await expect(popup.getByTestId('polygon-map-label')).toHaveCount(1)
  await page.getByTestId('reunite-windows').click()
})
