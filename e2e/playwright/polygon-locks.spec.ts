import { expect, test, type Page } from '@playwright/test'

test.use({ viewport: { width: 1280, height: 800 }, hasTouch: true })
type TestWindow = typeof window & { polygonTestApi: {
  getDrawingState(): { ready: boolean }
  getSelectedScreenPoints(): { vertices: Array<{ x: number; y: number }> }
  waitForPersistence(): Promise<void>
} }

async function create(page: Page, offset = 0, locked = false) {
  const before = await page.getByTestId('polygon-item').count()
  const box = await page.getByTestId('arcgis-map').boundingBox()
  if (!box) throw new Error('Mapa ausente')
  await page.getByTestId('draw-polygon').click()
  await expect.poll(() => page.evaluate(() => (window as TestWindow).polygonTestApi.getDrawingState().ready)).toBe(true)
  if (locked) await page.getByTestId('polygon-locked').check()
  for (const [x, y] of [[-55, -45], [55, -45], [0, 65]]) {
    await page.mouse.click(box.x + box.width / 2 + offset + x, box.y + box.height / 2 + y)
    await page.waitForTimeout(130)
  }
  await page.getByTestId('finish-drawing').click()
  await expect(page.getByTestId('polygon-item')).toHaveCount(before + 1)
  await expect(page.getByTestId('finish-drawing')).toBeHidden()
}

async function touchPolygon(page: Page, name: string) {
  const box = await page.getByTestId('polygon-map-label').filter({ hasText: name }).boundingBox()
  if (!box) throw new Error(`Nome ausente: ${name}`)
  await page.touchscreen.tap(box.x + box.width / 2, box.y + box.height / 2)
  // Separar toques simples: duas tentativas rápidas no mesmo ponto acionam o zoom por duplo toque.
  await page.waitForTimeout(400)
}

async function dragVertex(page: Page) {
  const box = await page.getByTestId('arcgis-map').boundingBox()
  const vertex = await page.evaluate(() => (window as TestWindow).polygonTestApi.getSelectedScreenPoints().vertices[0])
  if (!box) throw new Error('Mapa ausente')
  await page.waitForTimeout(350)
  await page.mouse.move(box.x + vertex.x, box.y + vertex.y)
  await page.mouse.down()
  await page.waitForTimeout(150)
  await page.mouse.move(box.x + vertex.x - 35, box.y + vertex.y + 30, { steps: 8 })
  await page.mouse.up()
  await expect(page.getByTestId('last-edit')).toHaveText('Vértice ou aresta arrastada.')
}

async function persist(page: Page) {
  await page.evaluate(() => (window as TestWindow).polygonTestApi.waitForPersistence())
}

test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(page.getByTestId('map-ready')).toBeVisible()
})

test('toque edita imediatamente; trocar permite salvar, descartar ou continuar a edição', async ({ page }) => {
  await create(page, -150)
  await create(page, 150)
  await touchPolygon(page, 'Polígono 1')
  await expect(page.getByTestId('polygon-name')).toHaveValue('Polígono 1')
  const original = await page.locator('.vertex-list').innerText()
  await page.getByTestId('polygon-name').fill('Reserva Salva')
  await dragVertex(page)
  const changed = await page.locator('.vertex-list').innerText()
  expect(changed).not.toBe(original)
  await touchPolygon(page, 'Polígono 2')
  await expect(page.locator('#switch-edit-dialog')).toBeVisible()
  await page.locator('#dismiss-switch').click()
  await expect(page.getByTestId('polygon-name')).toHaveValue('Reserva Salva')
  await touchPolygon(page, 'Polígono 2')
  await page.locator('#save-and-switch').click()
  await expect(page.getByTestId('polygon-name')).toHaveValue('Polígono 2')
  const secondOriginal = await page.locator('.vertex-list').innerText()
  await page.getByTestId('polygon-name').fill('Nome Descartado')
  await dragVertex(page)
  await expect.poll(() => page.locator('.vertex-list').innerText()).not.toBe(secondOriginal)
  await touchPolygon(page, 'Reserva Salva')
  await page.locator('#discard-and-switch').click()
  await expect(page.getByTestId('polygon-name')).toHaveValue('Reserva Salva')
  await expect(page.locator('.vertex-list')).toHaveText(changed, { useInnerText: true })
  await page.getByTestId('finish-drawing').click()
  await touchPolygon(page, 'Polígono 2')
  await expect(page.getByTestId('polygon-name')).toHaveValue('Polígono 2')
  await expect(page.locator('.vertex-list')).toHaveText(secondOriginal, { useInnerText: true })
  await page.getByTestId('cancel-editing').click()
  await persist(page)
  await page.reload()
  await expect(page.getByTestId('map-ready')).toBeVisible()
  await expect(page.getByTestId('polygon-map-label').filter({ hasText: 'Reserva Salva' })).toBeVisible()
})

test('troca não salva nome inválido e Escape mantém a edição atual', async ({ page }) => {
  await create(page, -150)
  await create(page, 150)
  await touchPolygon(page, 'Polígono 1')
  await page.getByTestId('polygon-name').fill('Nome!')
  await touchPolygon(page, 'Polígono 2')
  await page.locator('#save-and-switch').click()
  await expect(page.getByRole('alert')).toContainText('Use apenas letras')
  await expect(page.getByTestId('polygon-name')).toHaveValue('Nome!')
  await touchPolygon(page, 'Polígono 2')
  await page.keyboard.press('Escape')
  await expect(page.locator('#switch-edit-dialog')).toBeHidden()
  await expect(page.getByTestId('polygon-name')).toHaveValue('Nome!')
})

test('cria travado, só seleciona pela lista, impede edição, persiste e destrava', async ({ page }) => {
  await create(page, 0, true)
  const item = page.getByTestId('polygon-item')
  await expect(item.getByTestId('toggle-polygon-lock')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.polygon-badge')).toHaveCount(0)
  await touchPolygon(page, 'Polígono 1')
  await page.waitForTimeout(350)
  await expect(item).not.toHaveClass(/selected/)
  await expect(page.locator('.polygon-map-label.is-selected')).toHaveCount(0)
  await expect(page.locator('.vertex-list')).toHaveCount(0)
  await expect(page.getByTestId('draw-polygon')).toHaveAttribute('data-mode', 'create')
  await item.locator('.polygon-label').click()
  await expect(page.locator('.vertex-list')).toHaveCount(0)
  await item.getByTestId('expand-polygon').click()
  await expect(item).toHaveClass(/selected/)
  await expect(page.getByTestId('finish-drawing')).toBeHidden()
  await expect(page.getByTestId('draw-polygon')).toBeDisabled()
  await page.locator('#map .esri-view-surface').focus()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('finish-drawing')).toBeHidden()
  const before = await page.locator('.vertex-list').innerText()
  const box = await page.getByTestId('arcgis-map').boundingBox()
  const point = await page.evaluate(() => (window as TestWindow).polygonTestApi.getSelectedScreenPoints().vertices[0])
  if (!box) throw new Error('Mapa ausente')
  await page.mouse.move(box.x + point.x, box.y + point.y)
  await page.mouse.down()
  await page.mouse.move(box.x + point.x + 40, box.y + point.y + 30, { steps: 8 })
  await page.mouse.up()
  await expect(page.locator('.vertex-list')).toHaveText(before, { useInnerText: true })
  await persist(page)
  await page.reload()
  await expect(page.getByTestId('map-ready')).toBeVisible()
  await expect(item.getByTestId('toggle-polygon-lock')).toHaveAttribute('aria-pressed', 'true')
  await item.getByTestId('expand-polygon').click()
  await item.getByTestId('toggle-polygon-lock').click()
  await expect(item.getByTestId('toggle-polygon-lock')).toHaveAttribute('aria-pressed', 'false')
  await touchPolygon(page, 'Polígono 1')
  await expect(page.getByTestId('polygon-name')).toBeVisible()
  await dragVertex(page)
  await page.getByTestId('finish-drawing').click()
  await expect(page.locator('.vertex-list')).not.toHaveText(before, { useInnerText: true })
})

test('travar durante edição só vale ao salvar e Cancelar restaura nome e bloqueio', async ({ page }) => {
  await create(page)
  await touchPolygon(page, 'Polígono 1')
  await page.getByTestId('polygon-locked').check()
  await page.getByTestId('polygon-name').fill('Descartado')
  await page.getByTestId('cancel-editing').click()
  await expect(page.getByTestId('toggle-polygon-lock')).toHaveAttribute('aria-pressed', 'false')
  await touchPolygon(page, 'Polígono 1')
  await expect(page.getByTestId('polygon-locked')).not.toBeChecked()
  await page.getByTestId('polygon-locked').check()
  await page.getByTestId('polygon-name').fill('Área Protegida')
  await page.getByTestId('finish-drawing').click()
  await touchPolygon(page, 'Área Protegida')
  await expect(page.getByTestId('finish-drawing')).toBeHidden()
  await expect(page.getByTestId('toggle-polygon-lock')).toHaveAttribute('aria-pressed', 'true')
})

test('duas telas sincronizam troca de edição e bloqueio com destravamento no menu lateral', async ({ page }) => {
  await create(page, -150)
  await create(page, 150)
  const pendingPopup = page.waitForEvent('popup')
  await page.getByTestId('detach-map').click()
  const popup = await pendingPopup
  await expect(page.locator('#connection-status')).toContainText('Mapa conectado')
  await touchPolygon(popup, 'Polígono 1')
  await expect(page.getByTestId('polygon-name')).toHaveValue('Polígono 1')
  await page.getByTestId('polygon-name').fill('Reserva')
  await page.getByTestId('polygon-locked').check()
  await expect(popup.getByTestId('polygon-locked')).toBeChecked()
  await touchPolygon(popup, 'Polígono 2')
  await expect(page.locator('#switch-edit-dialog')).toBeVisible()
  await page.locator('#save-and-switch').click()
  await expect(popup.getByTestId('polygon-name')).toHaveValue('Polígono 2')
  await expect(page.getByTestId('polygon-item').first().getByTestId('toggle-polygon-lock')).toHaveAttribute('aria-pressed', 'true')
  await popup.getByTestId('cancel-editing').click()
  await expect(page.getByTestId('finish-drawing')).toBeHidden()
  await touchPolygon(popup, 'Reserva')
  await popup.waitForTimeout(350)
  await expect(page.getByTestId('polygon-item').first()).not.toHaveClass(/selected/)
  await expect(page.getByTestId('polygon-item').last()).toHaveClass(/selected/)
  await expect(popup.locator('.polygon-map-label.is-selected')).toHaveText('Polígono 2')
  await expect(popup.getByTestId('finish-drawing')).toBeHidden()
  await page.getByTestId('polygon-item').first().getByTestId('toggle-polygon-lock').click()
  await expect(page.getByTestId('polygon-item').first().getByTestId('toggle-polygon-lock')).toHaveAttribute('aria-pressed', 'false')
  await touchPolygon(popup, 'Reserva')
  await expect(popup.getByTestId('polygon-name')).toHaveValue('Reserva')
  await page.getByTestId('cancel-editing').click()
  await expect(popup.getByTestId('finish-drawing')).toBeHidden()
  await page.getByTestId('reunite-windows').click()
  await expect(page.getByTestId('polygon-map-label').filter({ hasText: 'Reserva' })).toBeVisible()
})

test('toque em polígono travado preserva a seleção e a edição de outro sem abrir confirmação', async ({ page }) => {
  await create(page, -150, true)
  await create(page, 150)
  await touchPolygon(page, 'Polígono 2')
  await page.getByTestId('polygon-name').fill('Rascunho')
  await touchPolygon(page, 'Polígono 1')
  await page.waitForTimeout(350)
  await expect(page.locator('#switch-edit-dialog')).toBeHidden()
  await expect(page.getByTestId('polygon-name')).toHaveValue('Rascunho')
  await expect(page.getByTestId('polygon-item').last()).toHaveClass(/selected/)
  await expect(page.getByTestId('polygon-item').first()).not.toHaveClass(/selected/)
  await expect(page.locator('.polygon-badge')).toHaveCount(0)
  await page.getByTestId('cancel-editing').click()
  await expect(page.locator('.polygon-label').last()).toHaveText('Polígono 2')
  await page.getByTestId('polygon-item').first().locator('.polygon-label').click()
  await expect(page.getByTestId('polygon-item').first()).toHaveClass(/selected/)
  await expect(page.locator('.polygon-map-label.is-selected')).toHaveText('Polígono 1')
  await expect(page.getByTestId('finish-drawing')).toBeHidden()
})
