import { expect, test, type Page } from '@playwright/test'

test.use({ viewport: { width: 1280, height: 800 }, hasTouch: true })
type TestWindow = typeof window & { polygonTestApi: { getDrawingState(): { ready: boolean } } }

async function vertices(mapPage: Page, offset = 0) {
  await expect.poll(() => mapPage.evaluate(() => (window as TestWindow).polygonTestApi.getDrawingState().ready)).toBe(true)
  const box = await mapPage.getByTestId('arcgis-map').boundingBox()
  if (!box) throw new Error('Mapa ausente')
  for (const [x, y] of [[-50, -40], [50, -40], [0, 65]]) {
    await mapPage.mouse.click(box.x + box.width / 2 + offset + x, box.y + box.height / 2 + y)
    await mapPage.waitForTimeout(150)
  }
}

async function create(page: Page, offset = 0) {
  const count = await page.getByTestId('polygon-item').count()
  await page.getByTestId('draw-polygon').click()
  // A rolagem precisa de áreas independentes, sem acionar a fusão de duplicatas.
  await page.getByTestId('polygon-color-option').nth(count % 6).click()
  await vertices(page, offset + Math.floor(count / 6) * 150)
  await page.getByTestId('finish-drawing').click()
  await expect(page.getByTestId('polygon-item')).toHaveCount(count + 1)
}

async function expectFocused(page: Page) {
  await expect(page.locator('.collection-heading')).toBeHidden()
  await expect(page.locator('#empty-state')).toBeHidden()
  await expect(page.getByTestId('detach-map')).toBeHidden()
  await expect(page.locator('#polygon-file-actions')).toBeHidden()
  await expect(page.getByTestId('clear-polygons')).toBeHidden()
  await expect(page.getByTestId('draw-polygon')).toBeHidden()
  await expect(page.getByTestId('polygon-color-option')).toHaveCount(6)
  await expect(page.getByTestId('polygon-color-option').first()).toBeVisible()
  await expect(page.getByTestId('polygon-locked')).toBeVisible()
  await expect(page.getByTestId('finish-drawing')).toBeVisible()
  await expect(page.getByTestId('cancel-editing')).toBeVisible()
}

async function touch(page: Page, name: string) {
  const box = await page.getByTestId('polygon-map-label').filter({ hasText: name }).boundingBox()
  if (!box) throw new Error('Polígono ausente')
  await page.touchscreen.tap(box.x + box.width / 2, box.y + box.height / 2)
}

test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(page.getByTestId('map-ready')).toBeVisible()
})

test('cabeçalho mínimo e criação ocultam a coleção e restauram ações ao concluir ou cancelar', async ({ page }) => {
  await expect(page.locator('.sidebar-header > *')).toHaveCount(1)
  await expect(page.locator('.sidebar-header h1')).toHaveText('Polígonos')
  await expect(page.locator('.sidebar-header #polygon-count')).toHaveText('0')
  await expect(page.locator('.sidebar-header button')).toHaveCount(1)
  await expect(page.locator('.sidebar-header').getByTestId('install-app')).toBeAttached()
  await expect(page.locator('.sidebar-brand, .sidebar-description')).toHaveCount(0)
  await expect(page.locator('.sidebar-scroll')).toHaveCSS('overflow-y', 'scroll')
  await expect(page.getByRole('scrollbar', { name: 'Rolar menu lateral' })).toBeVisible()
  await page.getByTestId('draw-polygon').click()
  await expectFocused(page)
  await expect(page.locator('.sidebar-scroll')).toHaveCSS('overflow-y', 'scroll')
  await expect(page.getByRole('scrollbar', { name: 'Rolar menu lateral' })).toBeVisible()
  await page.getByTestId('cancel-editing').click()
  await expect(page.locator('#empty-state')).toBeVisible()
  await create(page, -150)
  await create(page, 150)
  await page.getByTestId('draw-polygon').click()
  await expectFocused(page)
  await expect(page.getByTestId('polygon-list')).toBeHidden()
  await expect(page.locator('#polygon-count')).toHaveText('2')
  await page.getByTestId('cancel-editing').click()
  await expect(page.locator('[data-testid="polygon-item"]:visible')).toHaveCount(2)
  await expect(page.getByTestId('detach-map')).toBeVisible()
  await page.getByTestId('draw-polygon').click()
  await vertices(page)
  await page.getByTestId('finish-drawing').click()
  await expect(page.locator('[data-testid="polygon-item"]:visible')).toHaveCount(3)
  await expect(page.locator('.collection-heading')).toBeVisible()
  await expect(page.getByTestId('detach-map')).toBeVisible()
})

test('edição mostra só o card atual e acompanha a troca de polígono pelo mapa', async ({ page }, testInfo) => {
  await create(page, -150)
  await create(page, 150)
  await touch(page, 'Polígono 1')
  await expectFocused(page)
  await expect(page.getByTestId('polygon-item').first()).toBeVisible()
  await expect(page.getByTestId('polygon-item').last()).toBeHidden()
  await expect(page.locator('[data-testid="polygon-item"]:visible')).toHaveCount(1)
  await page.getByTestId('polygon-name').fill('Reserva')
  await page.getByTestId('finish-drawing').click()
  await expect(page.locator('[data-testid="polygon-item"]:visible')).toHaveCount(2)
  await touch(page, 'Polígono 2')
  await expect(page.getByTestId('polygon-item').first()).toBeHidden()
  await expect(page.getByTestId('polygon-item').last()).toBeVisible()
  await page.getByTestId('polygon-name').fill('Rascunho')
  await touch(page, 'Reserva')
  await page.locator('#discard-and-switch').click()
  await expect(page.getByTestId('polygon-name')).toHaveValue('Reserva')
  await expect(page.getByTestId('polygon-item').first()).toBeVisible()
  await expect(page.getByTestId('polygon-item').last()).toBeHidden()
  await page.screenshot({ path: testInfo.outputPath('focused-sidebar.png') })
  await page.getByTestId('cancel-editing').click()
  await expect(page.locator('[data-testid="polygon-item"]:visible')).toHaveCount(2)
  await expect(page.locator('.polygon-label').last()).toHaveText('Polígono 2')
  await expect(page.getByTestId('clear-polygons')).toBeVisible()
})

test('contador fica ao lado do nome e rolagem da coleção mantém cabeçalho e ações acessíveis', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1280, height: 600 })
  await create(page)
  const item = page.getByTestId('polygon-item').first()
  const name = await item.locator('.polygon-label').boundingBox()
  const count = await item.locator('.polygon-meta').boundingBox()
  if (!name || !count) throw new Error('Nome ou contador ausente')
  await expect(item.locator('.polygon-meta')).toHaveText('3')
  await expect(item.locator('.polygon-meta')).toHaveAccessibleName('3 vértices')
  expect(count.width).toBe(count.height)
  expect(count.x).toBeGreaterThan(name.x + name.width)
  expect(count.y + count.height / 2).toBeCloseTo(name.y + name.height / 2, 1)
  await page.screenshot({ path: testInfo.outputPath('collapsed-counter-scrollbar.png') })
  for (let index = 0; index < 7; index++) await create(page)
  const scroller = page.locator('.sidebar-scroll')
  const header = await page.locator('.sidebar-header').boundingBox()
  const actions = await page.locator('.sidebar-actions').boundingBox()
  await scroller.hover()
  await page.mouse.wheel(0, 1000)
  await expect.poll(() => scroller.evaluate((element) => element.scrollTop)).toBeGreaterThan(0)
  await expect(page.getByTestId('polygon-item').last()).toBeInViewport()
  expect(await page.locator('.sidebar-header').boundingBox()).toEqual(header)
  expect(await page.locator('.sidebar-actions').boundingBox()).toEqual(actions)
  await expect(page.getByTestId('draw-polygon')).toBeInViewport()
  const bar = page.getByRole('scrollbar', { name: 'Rolar menu lateral' })
  await bar.press('Home')
  await expect.poll(() => scroller.evaluate((element) => element.scrollTop)).toBe(0)
  const thumb = await page.locator('.sidebar-scrollbar-thumb').boundingBox()
  const track = await bar.boundingBox()
  if (!thumb || !track) throw new Error('Barra de rolagem ausente')
  await page.mouse.move(thumb.x + thumb.width / 2, thumb.y + thumb.height / 2)
  await page.mouse.down()
  await page.mouse.move(thumb.x + thumb.width / 2, track.y + track.height - 2, { steps: 8 })
  await page.mouse.up()
  await expect.poll(() => scroller.evaluate((element) => element.scrollTop)).toBeGreaterThan(0)
  await expect(page.getByTestId('polygon-item').last()).toBeInViewport()
})

test('duas telas focam o polígono atual, ocultam ações das janelas e restauram ao finalizar', async ({ page }) => {
  await create(page, -150)
  await create(page, 150)
  const pendingPopup = page.waitForEvent('popup')
  await page.getByTestId('detach-map').click()
  const popup = await pendingPopup
  await expect(page.locator('#connection-status')).toContainText('Mapa conectado')
  await touch(popup, 'Polígono 1')
  await expectFocused(page)
  await expect(page.getByTestId('polygon-item').last()).toBeHidden()
  await expect(page.locator('#detached-tools')).toBeHidden()
  await expect(popup.getByTestId('return-map')).toBeHidden()
  await page.getByTestId('polygon-name').fill('Reserva')
  await touch(popup, 'Polígono 2')
  await page.locator('#save-and-switch').click()
  await expect(page.getByTestId('polygon-name')).toHaveValue('Polígono 2')
  await expect(page.getByTestId('polygon-item').first()).toBeHidden()
  await expect(page.getByTestId('polygon-item').last()).toBeVisible()
  await popup.getByTestId('cancel-editing').click()
  await expect(page.locator('[data-testid="polygon-item"]:visible')).toHaveCount(2)
  await expect(page.locator('#detached-tools')).toBeVisible()
  await expect(popup.getByTestId('return-map')).toBeVisible()
  await page.getByTestId('draw-polygon').focus()
  await page.keyboard.press('Escape')
  await page.getByTestId('draw-polygon').click()
  await expectFocused(page)
  await expect(page.getByTestId('polygon-list')).toBeHidden()
  await vertices(popup)
  await page.getByTestId('finish-drawing').click()
  await expect(page.locator('[data-testid="polygon-item"]:visible')).toHaveCount(3)
  await expect(page.locator('#detached-tools')).toBeVisible()
  await page.getByTestId('reunite-windows').click()
  await expect(page.getByTestId('detach-map')).toBeVisible()
})
